import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = resolve(root, 'dist/third-party-licenses.txt');

const distributed = new Set(['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'BlueOak-1.0.0', 'CC0-1.0', 'Python-2.0', 'OFL-1.1', 'Unlicense']);
const buildTimeOnly = new Set(['MPL-2.0', 'LGPL-3.0-or-later']);

const report = JSON.parse(execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));
const failures = [];
const packages = [];

for (const [licence, entries] of Object.entries(report)) {
  if (!distributed.has(licence) && !buildTimeOnly.has(licence)) {
    failures.push(`${licence} is not on the allowlist (${entries.map(entry => entry.name).join(', ')}); add it to docs/licence-policy.md deliberately, or remove the dependency`);
  }
  for (const entry of entries) packages.push({ ...entry, licence });
}
packages.sort((a, b) => a.name.localeCompare(b.name));

const licenceFileNames = /^(licen[cs]e|copying|ofl)(\.|$)/i;
function licenceText(entry) {
  for (const directory of entry.paths ?? []) {
    if (!existsSync(directory)) continue;
    const file = readdirSync(directory).find(name => licenceFileNames.test(name));
    if (file) return readFileSync(resolve(directory, file), 'utf8').trim();
  }
  return null;
}

const declaredOnly = [];
const blocks = [];
for (const entry of packages) {
  const text = licenceText(entry);
  if (!text) { declaredOnly.push(entry); continue; }
  blocks.push(`${'='.repeat(78)}\n${entry.name} ${entry.versions.join(', ')}\n${entry.licence}${entry.homepage ? ` · ${entry.homepage}` : ''}\n${'='.repeat(78)}\n\n${text}\n`);
}

const distDirectory = resolve(root, 'dist');
if (existsSync(distDirectory)) {
  const shipped = [];
  const walk = directory => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = resolve(directory, entry.name);
      if (entry.isDirectory()) walk(path);
      else if (/\.(node|dylib|so|dll)$/.test(entry.name) || /libvips|lightningcss/i.test(entry.name)) shipped.push(path.slice(distDirectory.length + 1));
    }
  };
  walk(distDirectory);
  if (shipped.length) {
    failures.push(`build-time-only dependencies reached dist/: ${shipped.join(', ')}. ${[...buildTimeOnly].join(' and ')} are allowlisted only because they are never conveyed; if they ship, the exception in docs/licence-policy.md no longer applies.`);
  }
}

if (failures.length) {
  process.stderr.write('Third-party licences\n' + failures.map(line => `  ${line}`).join('\n') + '\n');
  process.exitCode = 1;
} else {
  mkdirSync(resolve(root, 'dist'), { recursive: true });
  const summary = packages.map(entry => `  ${entry.licence.padEnd(18)} ${entry.name} ${entry.versions.join(', ')}`).join('\n');
  const declared = declaredOnly.length
    ? `\n${'-'.repeat(78)}\nDeclared licence, no licence file in the published package\n${'-'.repeat(78)}\n\nThese packages name their licence in package.json but ship no licence text. The\nstandard text of the named licence applies; the authors are credited here.\n\n${declaredOnly.map(entry => `  ${entry.licence.padEnd(18)} ${entry.name} ${entry.versions.join(', ')}${entry.author ? ` — ${entry.author}` : ''}`).join('\n')}\n`
    : '';
  writeFileSync(output, `Third-party licences bundled with this site
${'-'.repeat(78)}

This file lists every production dependency and reproduces its licence. The web
fonts are the part that reaches a visitor's browser, and the SIL Open Font
Licence requires its text to travel with them; it is below.

Generated by scripts/third-party-licenses.mjs. Do not edit by hand.

${summary}
${declared}
${blocks.join('\n')}`);
  process.stdout.write(`Third-party licences: ${packages.length} production packages, ${new Set(packages.map(p => p.licence)).size} distinct licences, ${blocks.length} licence texts reproduced, ${declaredOnly.length} declared without text; written to dist/third-party-licenses.txt\n`);
}
